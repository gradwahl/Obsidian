#!/usr/bin/env python3
"""Build a compact, verified artwork URL overlay from Obsidian-archive's Git tree.

This reads filenames only with a partial, checkout-free Git clone. It never
downloads or copies the artwork blobs. A same-console exact normalized title
is required; ambiguous editions are skipped. No Git credentials are embedded
in the generated files. Public HTTP accessibility must be configured
separately before console/browser streaming will work.
"""
from __future__ import annotations

import argparse
import collections
import json
import re
import subprocess
import tempfile
import unicodedata
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/gradwahl/Obsidian-archive.git"
RAW = "https://raw.githubusercontent.com/gradwahl/Obsidian-archive/main/"
OUTPUT_JSON = ROOT / "src/archiveArtworkUrls.json"
OUTPUT_C = ROOT / "src/archive_artwork_index.h"
HASH_SUFFIX = re.compile(r"\s*\[[0-9a-f]{16}\]$", re.I)
CONSOLES = {
    "PPSA": "Sony/PlayStation 5",
    "CUSA": "Sony/PlayStation 4",
}


def normalize(title: str) -> str:
    title = HASH_SUFFIX.sub("", title)
    title = unicodedata.normalize("NFKD", title).casefold()
    return "".join(char for char in title if char.isalnum())


def encode_path(path: str, base_url: str = RAW) -> str:
    return base_url.rstrip("/") + "/" + "/".join(
        urllib.parse.quote(part, safe="") for part in path.split("/")
    )


def tree_paths() -> list[str]:
    with tempfile.TemporaryDirectory(prefix="obsidian-artwork-tree-") as directory:
        cloned = subprocess.run(
            ["git", "clone", "--filter=blob:none", "--depth=1", "--no-checkout",
             "--single-branch", REPO, directory],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
            encoding="utf-8", errors="replace", timeout=100,
        )
        if cloned.returncode:
            raise RuntimeError("Cannot read archive tree: " + cloned.stderr[-2000:])
        listed = subprocess.run(
            ["git", "-C", directory, "ls-tree", "-rz", "--name-only", "HEAD"],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=50, check=True,
        )
        return [name.decode("utf-8", "replace")
                for name in listed.stdout.split(b"\0") if name]


def build(paths: list[str], catalog: list[dict], base_url: str = RAW) -> tuple[dict[str, str], dict]:
    candidates = collections.defaultdict(list)
    for path in paths:
        if not path.lower().endswith(".art"):
            continue
        for console in CONSOLES.values():
            prefix = "assets/covers/" + console + "/"
            if path.startswith(prefix):
                name = path[len(prefix):-4]
                if "/" not in name:
                    candidates[(console, normalize(name))].append((path, name))
                break

    matched: dict[str, str] = {}
    skipped = collections.Counter()
    for game in catalog:
        code = str(game.get("id_code", ""))
        title = str(game.get("title", ""))
        console = CONSOLES.get(code[:4].upper())
        if not console or not title:
            skipped["unsupported_console"] += 1
            continue
        options = candidates.get((console, normalize(title)), [])
        untagged = [(path, name) for path, name in options
                    if not HASH_SUFFIX.search(name)]
        if len(untagged) == 1:
            selected = untagged[0][0]
        elif len(options) == 1:
            selected = options[0][0]
        else:
            skipped["ambiguous" if options else "no_match"] += 1
            continue
        url = encode_path(selected, base_url)
        if len(url.encode("utf8")) >= 512:
            skipped["url_too_long"] += 1
            continue
        key = code + "|" + title
        old = matched.get(key)
        if old and old != url:
            skipped["key_collision"] += 1
            del matched[key]
        elif not old:
            matched[key] = url
    return dict(sorted(matched.items())), dict(skipped)


def save(matched: dict[str, str]) -> None:
    OUTPUT_JSON.write_text(
        json.dumps(matched, ensure_ascii=False, indent=2) + "\n",
        encoding="utf8", newline="\n",
    )
    rows = [
        "/* Generated by scripts/generate_archive_artwork.py. Filename-only matches. */",
        "#ifndef OBSIDIAN_ARCHIVE_ARTWORK_INDEX_H",
        "#define OBSIDIAN_ARCHIVE_ARTWORK_INDEX_H",
        "typedef struct { const char *id, *title, *url; } ArchiveArtworkMatch;",
        "static const ArchiveArtworkMatch ARCHIVE_ARTWORK_MATCHES[] = {",
    ]
    for key, url in matched.items():
        game_id, title = key.split("|", 1)
        fields = (game_id, title, url)
        rows.append("    {" + ", ".join(
            json.dumps(value, ensure_ascii=False) for value in fields
        ) + "},")
    rows.extend([
        "};",
        "#define ARCHIVE_ARTWORK_MATCH_COUNT "
        "(sizeof(ARCHIVE_ARTWORK_MATCHES) / sizeof(ARCHIVE_ARTWORK_MATCHES[0]))",
        "#endif",
        "",
    ])
    OUTPUT_C.write_text("\n".join(rows), encoding="utf8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tree-list", type=Path,
                        help="Use a newline-delimited git tree listing instead of cloning")
    parser.add_argument("--base-url", default=RAW,
                        help="Public HTTPS origin preserving the assets/covers paths")
    args = parser.parse_args()
    paths = (args.tree_list.read_text("utf8").splitlines()
             if args.tree_list else tree_paths())
    catalog = json.loads((ROOT / "src/catalogData.json").read_text("utf8"))
    base = urllib.parse.urlsplit(args.base_url)
    if base.scheme != "https" or not base.netloc or base.username or base.password or base.query or base.fragment:
        parser.error("--base-url must be a public HTTPS URL without credentials, query or fragment")
    matched, skipped = build(paths, catalog, args.base_url)
    save(matched)
    print(f"Archive artwork: {len(matched)} safe matches / {len(catalog)} game rows")
    print(f"Unmatched: {skipped}")
    print("Only path metadata was generated; remote artwork remains on GitHub.")
    print("IMPORTANT: The archive must allow unauthenticated HTTP GETs for PS5 streaming.")


if __name__ == "__main__":
    main()
